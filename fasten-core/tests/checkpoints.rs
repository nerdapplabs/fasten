//! Chain checkpoints (spec/chain-replication.md §9): the cross-SDK vectors
//! in spec/checkpoint-vectors.json, the line format, and the cases a chain
//! alone cannot show.
//!
//! The Postgres test needs `FASTEN_TEST_POSTGRES_DSN` and passes without it.

use std::path::Path;

use chrono::{DateTime, Utc};
use fasten_core::chain::{seal, verify_chain, verify_chain_with_checkpoints, ChainRow, ChainVerifyResult, Json};
use fasten_core::checkpoint::{checkpoints_of, checkpoints_since, Checkpoint, CheckpointError, CheckpointOptions};

const WHOLE: CheckpointOptions = CheckpointOptions { partial: false };
const PARTIAL: CheckpointOptions = CheckpointOptions { partial: true };

fn base_row(node: &str, seq: u64, qty: u64) -> ChainRow {
    ChainRow::from_json(&format!(
        r#"{{"wire_version": "1", "id": "evt-{node}-{seq}", "origin_id": "evt-{node}-{seq}",
            "monotonic_seq": {seq}, "timestamp": "2026-06-15T10:30:00.000000Z",
            "code": "ORDER_PLACED", "action": "create", "severity": "info",
            "service_id": "gateway", "source_node_id": "{node}", "tenant_id": null,
            "actor": "alice", "actor_kind": "user", "target": "order/{seq}",
            "category": "order", "domain": "sales", "method": "http",
            "request_id": "req-{seq}", "detail": {{"qty": {qty}}}}}"#
    ))
    .unwrap()
}

/// A sealed chain on `node`, seq 1 to n, with `qty` in each row's detail.
fn chain_with(node: &str, n: u64, qty: u64) -> Vec<ChainRow> {
    let mut out: Vec<ChainRow> = Vec::new();
    for seq in 1..=n {
        let prev = out.last().map_or("genesis", |r| r.hash.as_str()).to_string();
        out.push(seal(&prev, &base_row(node, seq, qty)).unwrap());
    }
    out
}

fn chain(n: u64) -> Vec<ChainRow> {
    chain_with("node-1", n, 1)
}

fn at(ts: &str) -> DateTime<Utc> {
    ts.parse().unwrap()
}

fn cp_at(row: &ChainRow, anchored_at: &str) -> Checkpoint {
    Checkpoint {
        source_node_id: row.source_node_id.clone(),
        monotonic_seq: row.monotonic_seq,
        hash: row.hash.clone(),
        anchored_at: anchored_at.to_string(),
    }
}

fn cp(row: &ChainRow) -> Checkpoint {
    cp_at(row, "2026-06-15T11:00:00.000000Z")
}

fn assert_breaks(res: &ChainVerifyResult, seq: u64, reason: &str) {
    assert!(!res.ok, "verified, wanted a break at {seq}");
    assert_eq!((res.first_break_at, res.reason.as_deref()), (Some(seq), Some(reason)));
}

// --- vectors generated by Python (scripts/gen_checkpoint_vectors.py) ---

#[test]
fn checkpoint_vectors_give_the_recorded_results() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../spec/checkpoint-vectors.json");
    let file = Json::parse(&std::fs::read_to_string(path).unwrap()).unwrap();
    let cases = file.get("cases").and_then(Json::as_array).unwrap();
    assert!(cases.len() >= 19, "only {} cases", cases.len());
    for case in cases {
        let label = case.get("label").and_then(Json::as_str).unwrap();
        let list = |key: &str| case.get(key).and_then(Json::as_array).unwrap();
        let rows: Vec<ChainRow> = list("rows").iter().map(|r| ChainRow::from_value(r).unwrap()).collect();
        // Each checkpoint goes through the line parser, as a file's would.
        let checkpoints: Vec<Checkpoint> = list("checkpoints")
            .iter()
            .map(|c| Checkpoint::from_json(&fasten_core::chain::canonical_json(c)).unwrap())
            .collect();
        let partial = case.get("partial") == Some(&Json::Bool(true));

        let expected = case.get("expected").unwrap();
        let want_ok = expected.get("ok") == Some(&Json::Bool(true));
        let want_at = match expected.get("first_break_at").unwrap() {
            Json::Number(tok) => Some(tok.parse::<u64>().unwrap()),
            Json::Null => None,
            other => panic!("{label}: first_break_at {other:?}"),
        };
        let want_reason = expected.get("reason").and_then(Json::as_str);

        let got = verify_chain_with_checkpoints(&rows, &checkpoints, CheckpointOptions { partial });
        assert_eq!(
            (got.ok, got.first_break_at, got.reason.as_deref()),
            (want_ok, want_at, want_reason),
            "{label}"
        );
        assert_eq!(got.total_rows, rows.len(), "{label}");
    }
}

// --- line format ---

#[test]
fn a_line_is_what_python_writes() {
    let cp = Checkpoint {
        source_node_id: "nœud-1".into(),
        monotonic_seq: 6,
        hash: "c68f".into(),
        anchored_at: "2026-06-15T11:00:00.000000Z".into(),
    };
    // json.dumps(cp.to_dict(), sort_keys=True)
    let line = r#"{"anchored_at": "2026-06-15T11:00:00.000000Z", "hash": "c68f", "monotonic_seq": 6, "source_node_id": "n\u0153ud-1"}"#;
    assert_eq!(cp.to_json(), line);
    assert_eq!(Checkpoint::from_json(line).unwrap(), cp);
    // Go writes the same object compact, in struct order.
    let go = r#"{"source_node_id":"nœud-1","monotonic_seq":6,"hash":"c68f","anchored_at":"2026-06-15T11:00:00.000000Z"}"#;
    assert_eq!(Checkpoint::from_json(go).unwrap(), cp);
}

#[test]
fn a_line_that_is_not_a_checkpoint_is_rejected() {
    let good = r#"{"source_node_id": "n", "monotonic_seq": 1, "hash": "h", "anchored_at": "t"}"#;
    assert!(Checkpoint::from_json(good).is_ok());
    for bad in [
        // another key, a key in other case, a missing key
        r#"{"source_node_id": "n", "monotonic_seq": 1, "hash": "h", "anchored_at": "t", "x": 1}"#,
        r#"{"Source_Node_ID": "n", "monotonic_seq": 1, "hash": "h", "anchored_at": "t"}"#,
        r#"{"source_node_id": "n", "monotonic_seq": 1, "hash": "h"}"#,
        // a value of another type
        r#"{"source_node_id": "n", "monotonic_seq": "1", "hash": "h", "anchored_at": "t"}"#,
        r#"{"source_node_id": "n", "monotonic_seq": 1.0, "hash": "h", "anchored_at": "t"}"#,
        r#"{"source_node_id": "n", "monotonic_seq": true, "hash": "h", "anchored_at": "t"}"#,
        r#"{"source_node_id": "n", "monotonic_seq": -1, "hash": "h", "anchored_at": "t"}"#,
        r#"{"source_node_id": null, "monotonic_seq": 1, "hash": "h", "anchored_at": "t"}"#,
        r#"{"source_node_id": "n", "monotonic_seq": 1, "hash": 7, "anchored_at": "t"}"#,
        r#"{"source_node_id": "n", "monotonic_seq": 1, "hash": "h", "anchored_at": null}"#,
        r#"[{"source_node_id": "n", "monotonic_seq": 1, "hash": "h", "anchored_at": "t"}]"#,
        r#"{"source_node_id": "n", "monotonic_seq": 1, "hash": "h", "anchor"#,
        "null",
        "",
    ] {
        assert!(matches!(Checkpoint::from_json(bad), Err(CheckpointError::NotACheckpoint(_))), "{bad}");
    }
}

// --- what a chain alone cannot show ---

#[test]
fn a_checkpoint_at_the_tip_verifies() {
    let rows = chain(6);
    let res = verify_chain_with_checkpoints(&rows, &[cp(&rows[1]), cp(&rows[5])], WHOLE);
    assert_eq!(res, ChainVerifyResult { ok: true, total_rows: 6, first_break_at: None, reason: None });
}

#[test]
fn a_cut_off_tail_is_caught_only_with_checkpoints() {
    let rows = chain(10);
    let cut = &rows[..6];
    assert!(verify_chain(cut).ok);
    let res = verify_chain_with_checkpoints(cut, &[cp(&rows[9])], WHOLE);
    assert_breaks(&res, 7, "node 'node-1': chain ends at seq 6 before checkpoint at seq 10");
    // A page ends before the tip without being cut.
    assert!(verify_chain_with_checkpoints(cut, &[cp(&rows[9])], PARTIAL).ok);
}

#[test]
fn a_chain_resealed_from_genesis_is_caught_only_with_checkpoints() {
    let rows = chain(6);
    let resealed = chain_with("node-1", 6, 2);
    assert!(verify_chain(&resealed).ok);
    for opts in [WHOLE, PARTIAL] {
        let res = verify_chain_with_checkpoints(&resealed, &[cp(&rows[4])], opts);
        assert_breaks(&res, 5, "row evt-node-1-5: hash differs from checkpoint at seq 5");
    }
}

#[test]
fn a_checkpoint_below_the_oldest_row_fails_a_whole_chain_verify() {
    let rows = chain(10);
    let cps = [cp(&rows[1]), cp(&rows[9])];
    let res = verify_chain_with_checkpoints(&rows[4..], &cps, WHOLE);
    assert_breaks(&res, 5, "node 'node-1': rows start at seq 5, after the checkpoint at seq 2");
    assert!(verify_chain_with_checkpoints(&rows[4..], &cps, PARTIAL).ok);
}

#[test]
fn a_row_missing_inside_the_rows_is_named_by_its_checkpoint() {
    let mut rows = chain(6);
    let gone = rows.remove(2);
    // The chain breaks at seq 4, where prev_hash no longer matches; the
    // checkpoint break at seq 3 is lower.
    let res = verify_chain_with_checkpoints(&rows, &[cp(&gone)], WHOLE);
    assert_breaks(&res, 3, "node 'node-1': no row at checkpointed seq 3");
}

#[test]
fn a_chain_break_wins_at_the_same_seq() {
    let mut rows = chain(6);
    let tip = cp(&rows[5]);
    rows[5].target = "order/other".into();
    rows[5].hash = "0".repeat(64);
    let res = verify_chain_with_checkpoints(&rows, &[tip], WHOLE);
    assert_breaks(&res, 6, "row evt-node-1-6: hash mismatch");
}

#[test]
fn a_checkpointed_node_must_have_rows_in_a_whole_chain_verify() {
    let rows = chain(3);
    let other = chain_with("node-2", 4, 1);
    let cps = [cp(&other[1]), cp(&other[3]), cp(&rows[2])];
    let res = verify_chain_with_checkpoints(&rows, &cps, WHOLE);
    assert_breaks(&res, 4, "node 'node-2': no rows, but checkpointed at seq 4");
    assert!(verify_chain_with_checkpoints(&rows, &cps, PARTIAL).ok);

    let res = verify_chain_with_checkpoints(&[], &cps[..2], WHOLE);
    assert_eq!(res.total_rows, 0);
    assert_breaks(&res, 4, "node 'node-2': no rows, but checkpointed at seq 4");
    assert!(verify_chain_with_checkpoints(&[], &cps, PARTIAL).ok);
    assert!(verify_chain_with_checkpoints(&[], &[], WHOLE).ok);
}

#[test]
fn the_lowest_break_across_nodes_is_reported() {
    let a = chain_with("node-a", 8, 1);
    let b = chain_with("node-b", 8, 1);
    let rows: Vec<ChainRow> = a[..5].iter().chain(&b[..3]).cloned().collect();
    let res = verify_chain_with_checkpoints(&rows, &[cp(&a[7]), cp(&b[7])], WHOLE);
    assert_breaks(&res, 4, "node 'node-b': chain ends at seq 3 before checkpoint at seq 8");
}

#[test]
fn rows_after_the_newest_checkpoint_are_not_covered() {
    let rows = chain(6);
    assert!(verify_chain_with_checkpoints(&rows[..5], &[cp(&rows[3])], WHOLE).ok);
}

// --- retention ---

#[test]
fn checkpoints_since_keeps_those_at_or_after_the_cutoff() {
    let rows = chain(3);
    let cps = [
        cp_at(&rows[0], "2026-06-15T11:00:00.000000Z"),
        cp_at(&rows[1], "2026-06-15T12:00:00.000000Z"),
        cp_at(&rows[2], "2026-06-15T13:00:00.000000Z"),
    ];
    assert_eq!(checkpoints_since(&cps, at("2026-06-15T12:00:00Z")).unwrap(), cps[1..]);
    // The cutoff is compared in UTC to the microsecond.
    assert_eq!(checkpoints_since(&cps, at("2026-06-15T14:00:00+02:00")).unwrap(), cps[1..]);
    assert_eq!(checkpoints_since(&cps, at("2026-06-15T12:00:00.000001Z")).unwrap(), cps[2..]);
    assert_eq!(checkpoints_since(&cps, at("2026-06-15T12:00:00.0000009Z")).unwrap(), cps[1..]);
    assert_eq!(checkpoints_since(&cps, at("2026-01-01T00:00:00Z")).unwrap(), cps);
    assert!(checkpoints_since(&cps, at("2027-01-01T00:00:00Z")).unwrap().is_empty());
}

#[test]
fn checkpoints_since_rejects_a_timestamp_not_in_the_canonical_form() {
    let rows = chain(1);
    for bad in ["2026-06-15T11:00:00Z", "2026-06-15T11:00:00.000000+00:00", "yesterday", ""] {
        let err = checkpoints_since(&[cp_at(&rows[0], bad)], at("2026-01-01T00:00:00Z")).unwrap_err();
        assert_eq!(
            err,
            CheckpointError::AnchoredAt { node: "node-1".into(), seq: 1, anchored_at: bad.into() }
        );
    }
}

#[test]
fn a_purged_chain_verifies_with_the_checkpoints_since_the_purge() {
    let rows = chain(10);
    let cps = [
        cp_at(&rows[1], "2026-06-15T11:00:00.000000Z"),
        cp_at(&rows[9], "2026-06-15T13:00:00.000000Z"),
    ];
    let kept = &rows[4..];
    assert!(!verify_chain_with_checkpoints(kept, &cps, WHOLE).ok);
    let since = checkpoints_since(&cps, at("2026-06-15T12:00:00Z")).unwrap();
    assert!(verify_chain_with_checkpoints(kept, &since, WHOLE).ok);
}

#[test]
fn checkpoints_of_takes_one_per_node() {
    let a = chain_with("node-a", 3, 1);
    let b = chain_with("node-b", 2, 1);
    let mut twin = b[1].clone();
    twin.id = "evt-node-b-twin".into();
    let tips = [a[2].clone(), b[1].clone(), twin];
    let cps = checkpoints_of(&tips, at("2026-06-15T11:00:00.5+00:00"));
    assert_eq!(cps, [cp_at(&a[2], "2026-06-15T11:00:00.500000Z"), cp_at(&b[1], "2026-06-15T11:00:00.500000Z")]);
}

// --- chain tips from the stores ---

#[cfg(any(feature = "sqlite", feature = "postgres"))]
mod stores {
    use super::*;
    use fasten_core::{Filter, Row, Store};

    fn row(id: &str, node: &str) -> Row {
        Row {
            wire_version: "1".into(),
            id: id.into(),
            origin_id: id.into(),
            timestamp: "2026-05-07T00:00:00.000000Z".into(),
            code: "USER_LOGIN".into(),
            action: "login".into(),
            severity: "info".into(),
            service_id: "svc".into(),
            source_node_id: node.into(),
            actor: "tester".into(),
            actor_kind: "user".into(),
            target: "res-1".into(),
            category: "test".into(),
            domain: "test".into(),
            method: "sdk".into(),
            request_id: "req-001".into(),
            detail: serde_json::json!({"setpoint": 75.0, "n": 7}),
            ..Default::default()
        }
    }

    /// Three nodes: one sealed, one whose newest row is unsealed, one with
    /// no sealed row at all.
    fn fill(store: &dyn Store, prefix: &str) {
        for i in 0..4 {
            store.insert(&row(&format!("{prefix}-b{i}"), &format!("{prefix}-node-b"))).unwrap();
        }
        for i in 0..3 {
            store.insert(&row(&format!("{prefix}-a{i}"), &format!("{prefix}-node-a"))).unwrap();
        }
        let unsealed = |id: &str, node: &str, seq| Row { monotonic_seq: seq, ..row(id, &format!("{prefix}-{node}")) };
        store.insert(&unsealed(&format!("{prefix}-a9"), "node-a", 9)).unwrap();
        store.insert(&unsealed(&format!("{prefix}-c1"), "node-c", 1)).unwrap();
    }

    fn assert_tips(store: &dyn Store, prefix: &str) {
        let tips: Vec<ChainRow> = store
            .chain_tips()
            .unwrap()
            .into_iter()
            .filter(|t| t.source_node_id.starts_with(prefix))
            .collect();
        let got: Vec<(&str, u64)> = tips.iter().map(|t| (t.source_node_id.as_str(), t.monotonic_seq)).collect();
        let (a, b) = (format!("{prefix}-node-a"), format!("{prefix}-node-b"));
        assert_eq!(got, [(a.as_str(), 3), (b.as_str(), 4)]);
        assert!(tips.iter().all(|t| t.hash.len() == 64));

        // The tips are the rows a whole-chain verify ends at.
        let cps = checkpoints_of(&tips, Utc::now());
        let all: Vec<ChainRow> = [&a, &b]
            .iter()
            .flat_map(|n| {
                store.chain_rows(&Filter { source_node_id: Some((*n).clone()), ..Default::default() }).unwrap()
            })
            .collect();
        let sealed: Vec<ChainRow> = all.iter().filter(|r| !r.hash.is_empty()).cloned().collect();
        assert!(verify_chain_with_checkpoints(&sealed, &cps, WHOLE).ok);
        let cut: Vec<ChainRow> = sealed.iter().filter(|r| r.monotonic_seq < 4).cloned().collect();
        let res = verify_chain_with_checkpoints(&cut, &cps, WHOLE);
        assert_breaks(&res, 4, &format!("node '{b}': chain ends at seq 3 before checkpoint at seq 4"));
    }

    #[cfg(feature = "sqlite")]
    #[test]
    fn sqlite_chain_tips_are_each_nodes_last_sealed_row() {
        let store = fasten_core::SqliteStore::open(":memory:", "audit_log", false).unwrap();
        assert!(store.chain_tips().unwrap().is_empty());
        fill(&store, "t");
        assert_tips(&store, "t");
    }

    #[cfg(feature = "sqlite")]
    #[test]
    fn sqlite_insert_stored_returns_the_row_as_stored() {
        let store = fasten_core::SqliteStore::open(":memory:", "audit_log", false).unwrap();
        let first = store.insert_stored(&row("evt-1", "node-a")).unwrap();
        let second = store.insert_stored(&row("evt-2", "node-a")).unwrap();
        assert_eq!((first.monotonic_seq, second.monotonic_seq), (1, 2));
        assert_eq!(first.prev_hash.as_deref(), Some("genesis"));
        assert_eq!(second.prev_hash, first.hash);
        // A repeated id takes no seq and comes back as it was stored.
        let again = store.insert_stored(&row("evt-1", "node-a")).unwrap();
        assert_eq!((again.monotonic_seq, &again.hash, &again.detail_salt), (1, &first.hash, &first.detail_salt));
        // A row with a seq of its own is stored and returned as given.
        let own = Row { monotonic_seq: 7, ..row("evt-7", "node-a") };
        assert_eq!(store.insert_stored(&own).unwrap().hash, None);

        let rows = store.chain_rows(&Filter::default()).unwrap();
        let stored: Vec<(&str, &str)> = rows.iter().map(|r| (r.id.as_str(), r.hash.as_str())).collect();
        let hash = |r: &Row| r.hash.clone().unwrap();
        assert_eq!(stored, [("evt-1", hash(&first).as_str()), ("evt-2", hash(&second).as_str()), ("evt-7", "")]);
        assert!(verify_chain(&rows[..2]).ok);
    }

    #[cfg(feature = "postgres")]
    #[test]
    fn postgres_chain_tips_are_each_nodes_last_sealed_row() {
        let Ok(dsn) = std::env::var("FASTEN_TEST_POSTGRES_DSN") else {
            return;
        };
        let store = fasten_core::PostgresStore::connect(&dsn, "fasten_core_chain_tips").unwrap();
        let prefix = format!("t{}", std::process::id());
        fill(&store, &prefix);
        assert_tips(&store, &prefix);
    }
}
